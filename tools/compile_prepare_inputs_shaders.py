def compile_permutation(low_res, jitter, inv_depth):
    tmp_spv = f"tmp_{low_res}_{jitter}_{inv_depth}.spv"
    cmd = [
        NDK_GLSLC,
        "-fshader-stage=compute",
        "-c", SHADER_SRC,
        "-I", INCLUDE_DIR,
        "-DFFX_GPU=1",
        "-DFFX_GLSL=1",
        f"-DFFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS={low_res}",
        f"-DFFX_FSR3UPSCALER_OPTION_JITTERED_MOTION_VECTORS={jitter}",
        f"-DFFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH={inv_depth}",
        "-o", tmp_spv
    ]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"glslc failed for low_res={low_res}, jitter={jitter}, inv_depth={inv_depth}:")
        print(res.stderr)
        sys.exit(1)
    with open(tmp_spv, "rb") as f:
        data = f.read()
    os.remove(tmp_spv)
    return data

